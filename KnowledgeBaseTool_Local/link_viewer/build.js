#!/usr/bin/env node

import { readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync, readdirSync, statSync, mkdtempSync, rmSync, renameSync } from 'fs';
import { join, dirname } from 'path';
import { minify } from 'terser';
import postcss from 'postcss';
import cssnano from 'cssnano';
import { createHash } from 'crypto';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const SRC_DIR = __dirname;
const OUTPUT_DIR = join(__dirname, 'dist');
const LEGACY = process.argv.includes('--legacy');
const unknownArgs = process.argv.slice(2).filter(arg => arg !== '--legacy');
if (unknownArgs.length) throw new Error(`未知构建参数: ${unknownArgs.join(' ')}`);
// Build in isolation: a parse error or missing asset must not destroy dist.
const DIST_DIR = mkdtempSync(join(__dirname, '.build-'));

try {

// Runtime files referenced by index.html but not generated by the minifier.
const STATIC_RUNTIME_FILES = [
  'design-system.css',
  'loading-states.css',
  'scroll-performance.css',
  'platform_intro.css',
  'loading-manager.js',
  'login_bootstrap.js',
  'comparison_matrix.js'
];

// 创建dist目录
if (!existsSync(DIST_DIR)) {
  mkdirSync(DIST_DIR, { recursive: true });
}

console.log('🚀 开始构建...\n');

// 1. 压缩 JavaScript
console.log('📦 压缩 JavaScript...');
const jsFiles = ['app_v8.js'];

for (const file of jsFiles) {
  const srcPath = join(SRC_DIR, file);
  const content = readFileSync(srcPath, 'utf8');
  
  console.log(`  处理: ${file} (${(content.length / 1024).toFixed(1)} KB)`);
  
  const result = await minify(content, {
    compress: {
      drop_console: false,
      drop_debugger: true,
      passes: 2,
      pure_funcs: ['console.debug']
    },
    mangle: {
      toplevel: false,
      keep_fnames: false
    },
    format: {
      comments: false
    }
  });
  
  const minFile = file.replace('.js', '.min.js');
  const distPath = join(DIST_DIR, minFile);
  writeFileSync(distPath, result.code);
  
  const reduction = ((1 - result.code.length / content.length) * 100).toFixed(1);
  console.log(`  ✅ ${minFile} (${(result.code.length / 1024).toFixed(1)} KB, 减少 ${reduction}%)\n`);
}

// 2. 压缩 CSS
console.log('🎨 压缩 CSS...');
const cssFiles = ['styles.css', 'extra_styles.css'];

for (const file of cssFiles) {
  const srcPath = join(SRC_DIR, file);
  const content = readFileSync(srcPath, 'utf8');
  
  console.log(`  处理: ${file} (${(content.length / 1024).toFixed(1)} KB)`);
  
  // Parse CSS rather than rewriting whitespace inside strings and data URLs.
  const result = await postcss([cssnano({ preset: ['default', { normalizeUrl: false, svgo: false }] })])
    .process(content, { from: srcPath, map: false });
  const minified = result.css;
  
  const minFile = file.replace('.css', '.min.css');
  const distPath = join(DIST_DIR, minFile);
  writeFileSync(distPath, minified);
  
  const reduction = ((1 - minified.length / content.length) * 100).toFixed(1);
  console.log(`  ✅ ${minFile} (${(minified.length / 1024).toFixed(1)} KB, 减少 ${reduction}%)\n`);
}

// 3. 复制HTML文件并更新引用
console.log('📄 处理 HTML 文件...');
const htmlFiles = ['index.html', 'platform_intro.html', 'test_optimization.html'];

for (const file of htmlFiles) {
  const srcPath = join(SRC_DIR, file);
  let content = readFileSync(srcPath, 'utf8');
  
  // 更新JS引用
  content = content.replace(/\bapp_v8\.js(?:\?v=\d+)?/g, 'app_v8.min.js');
  
  // 更新CSS引用
  content = content.replace(/\bstyles\.css(?:\?v=\d+)?/g, 'styles.min.css');
  content = content.replace(/\bextra_styles\.css(?:\?v=\d+)?/g, 'extra_styles.min.css');
  for (const file of ['app_v8.min.js', 'styles.min.css', 'extra_styles.min.css']) {
    const digest = createHash('sha256').update(readFileSync(join(DIST_DIR, file))).digest('hex').slice(0, 12);
    content = content.replaceAll(file, `${file}?v=${digest}`);
  }
  
  const distPath = join(DIST_DIR, file);
  writeFileSync(distPath, content);

  
  console.log(`  ✅ ${file}`);
}

// 4. 复制vendor目录
console.log('\n📚 复制 vendor 目录...');
const vendorSrc = join(SRC_DIR, 'vendor');
const vendorDist = join(DIST_DIR, 'vendor');

function copyDir(src, dest) {
  if (!existsSync(dest)) {
    mkdirSync(dest, { recursive: true });
  }
  
  const entries = readdirSync(src);
  
  for (const entry of entries) {
    const srcPath = join(src, entry);
    const destPath = join(dest, entry);
    
    if (statSync(srcPath).isDirectory()) {
      copyDir(srcPath, destPath);
    } else {
      copyFileSync(srcPath, destPath);
    }
  }
}

copyDir(vendorSrc, vendorDist);
console.log('  ✅ vendor 目录已复制');

// Copy non-generated runtime dependencies so dist-only deployments have no 404s.
console.log('\n🧩 复制运行时依赖...');
for (const file of STATIC_RUNTIME_FILES) {
  const source = join(SRC_DIR, file);
  // Optional feature bundles are copied when present; legacy build fixtures
  // without the comparison workflow remain valid.
  if (!existsSync(source) && file === 'comparison_matrix.js') continue;
  if (!existsSync(source)) throw new Error(`缺少前端运行时依赖: ${file}`);
  copyFileSync(source, join(DIST_DIR, file));
  console.log(`  ✅ ${file}`);
}

// Every local JS/CSS reference must be available in a dist-only deployment.
for (const file of htmlFiles) {
  const html = readFileSync(join(DIST_DIR, file), 'utf8');
  for (const match of html.matchAll(/(?:src|href)=["']([^"']+)["']/g)) {
    const url = match[1];
    if (/^(?:[a-z]+:|\/\/|#)/i.test(url)) continue;
    const path = url.split(/[?#]/)[0].replace(/^\//, '');
    if (/\.(?:js|css)$/.test(path) && !existsSync(join(DIST_DIR, path))) {
      throw new Error(`${file} 引用的静态资源未打包: ${path}`);
    }
  }
}

// 6. 生成构建报告
console.log('\n📊 生成构建报告...');

const report = {
  buildTime: new Date().toISOString(),
  files: {
    js: jsFiles.map(f => {
      const original = statSync(join(SRC_DIR, f)).size;
      const minified = statSync(join(DIST_DIR, f.replace('.js', '.min.js'))).size;
      return {
        name: f,
        original: `${(original / 1024).toFixed(1)} KB`,
        minified: `${(minified / 1024).toFixed(1)} KB`,
        reduction: `${((1 - minified / original) * 100).toFixed(1)}%`
      };
    }),
    css: cssFiles.map(f => {
      const original = statSync(join(SRC_DIR, f)).size;
      const minified = statSync(join(DIST_DIR, f.replace('.css', '.min.css'))).size;
      return {
        name: f,
        original: `${(original / 1024).toFixed(1)} KB`,
        minified: `${(minified / 1024).toFixed(1)} KB`,
        reduction: `${((1 - minified / original) * 100).toFixed(1)}%`
      };
    })
  }
};

writeFileSync(join(DIST_DIR, 'build-report.json'), JSON.stringify(report, null, 2));

rmSync(OUTPUT_DIR, { recursive: true, force: true });
renameSync(DIST_DIR, OUTPUT_DIR);
// Compatibility is explicit: ordinary builds never overwrite tracked files.
if (LEGACY) {
  for (const file of ['app_v8.min.js', 'styles.min.css', 'extra_styles.min.css']) {
    copyFileSync(join(OUTPUT_DIR, file), join(SRC_DIR, file));
  }
  copyFileSync(join(OUTPUT_DIR, 'index.html'), join(SRC_DIR, 'index.prod.html'));
  console.log('兼容模式：已更新源码目录中的历史压缩文件。');
}

console.log('\n✅ 构建完成！');
console.log(`📁 输出目录: ${OUTPUT_DIR}`);
console.log('\n📊 压缩统计:');
console.log('JavaScript:');
report.files.js.forEach(f => {
  console.log(`  ${f.name}: ${f.original} → ${f.minified} (减少 ${f.reduction})`);
});
console.log('CSS:');
report.files.css.forEach(f => {
  console.log(`  ${f.name}: ${f.original} → ${f.minified} (减少 ${f.reduction})`);
});
} finally {
  rmSync(DIST_DIR, { recursive: true, force: true });
}
